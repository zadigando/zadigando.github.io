// ===== I18N =====
let currentLang = 'pt';

function applyLang(lang) {
  currentLang = lang;
  const t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (t[key] !== undefined) {
      el.placeholder = t[key];
    }
  });

  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
  localStorage.setItem('lang', lang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

function initLang() {
  const saved = localStorage.getItem('lang');
  if (saved && translations[saved]) {
    applyLang(saved);
  } else {
    const browserLang = (navigator.language || navigator.userLanguage || 'pt');
    applyLang(browserLang.toLowerCase().startsWith('pt') ? 'pt' : 'en');
  }
}

// ===== MOBILE MENU =====
function initMenu() {
  const menuBtn = document.getElementById('menu-btn');
  const navCenter = document.getElementById('nav-center');
  if (!menuBtn || !navCenter) return;

  menuBtn.setAttribute('aria-expanded', 'false');

  menuBtn.addEventListener('click', () => {
    navCenter.classList.toggle('open');
    menuBtn.setAttribute('aria-expanded', String(navCenter.classList.contains('open')));
  });

  navCenter.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
      navCenter.classList.remove('open');
      menuBtn.setAttribute('aria-expanded', 'false');
    });
  });

  document.addEventListener('click', e => {
    if (!menuBtn.contains(e.target) && !navCenter.contains(e.target)) {
      navCenter.classList.remove('open');
      menuBtn.setAttribute('aria-expanded', 'false');
    }
  });
}

// ===== REVEAL ON SCROLL =====
function initReveal() {
  const els = document.querySelectorAll('.reveal');
  if (!els.length) return;

  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.08 });

  els.forEach(el => observer.observe(el));
}

// ===== CONTACT FORM =====
function initContactForm() {
  const form = document.getElementById('contact-form');
  if (!form) return;

  form.addEventListener('submit', function (e) {
    e.preventDefault();
    const btn = form.querySelector('button[type="submit"]');
    const originalText = btn.textContent;
    btn.disabled = true;
    btn.textContent = '...';

    emailjs.send('service_oky71nr', 'template_hkb77uu', {
      name: document.getElementById('name').value,
      email: document.getElementById('email').value,
      message: document.getElementById('message').value,
    }).then(() => {
      btn.textContent = currentLang === 'pt' ? 'Enviado!' : 'Sent!';
      form.reset();
      setTimeout(() => {
        btn.disabled = false;
        btn.textContent = originalText;
      }, 3000);
    }).catch(err => {
      console.error(err);
      btn.disabled = false;
      btn.textContent = originalText;
      alert(currentLang === 'pt' ? 'Erro ao enviar. Tente novamente.' : 'Error sending. Please try again.');
    });
  });
}

// ===== INIT =====
document.addEventListener('DOMContentLoaded', () => {
  const yearEl = document.getElementById('year');
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  initLang();
  initMenu();
  initReveal();
  initContactForm();
});
